"""Helpers for PostgreSQL schema tests (T1.2). Fixtures live in ``conftest.py``."""

import datetime as dt
import uuid
from pathlib import Path
from typing import Any

from alembic.config import Config
from sqlalchemy import Connection, text

BACKEND_DIR = Path(__file__).resolve().parents[2]
NOW = dt.datetime(2026, 11, 26, 9, 30, tzinfo=dt.UTC)


def alembic_config(connection: Connection) -> Config:
    cfg = Config(str(BACKEND_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND_DIR / "migrations"))
    cfg.attributes["connection"] = connection
    return cfg


class Db:
    """Thin helper over one connection whose search_path is the test schema."""

    def __init__(self, connection: Connection, schema: str) -> None:
        self.conn = connection
        self.schema = schema
        self.alembic = alembic_config(connection)

    def scalar(self, sql: str, **params: Any) -> Any:
        return self.conn.execute(text(sql), params).scalar_one()

    def execute(self, sql: str, **params: Any) -> None:
        self.conn.execute(text(sql), params)

    def user(self, subject: str | None = None) -> uuid.UUID:
        return self.scalar(
            "INSERT INTO users (auth_subject) VALUES (:s) RETURNING id",
            s=subject or f"test-{uuid.uuid4()}",
        )

    def day_session(self, user_id: uuid.UUID) -> uuid.UUID:
        return self.scalar(
            "INSERT INTO day_sessions (user_id, local_date, timezone, status, started_at, sync_rev)"
            " VALUES (:u, :d, 'Asia/Kolkata', 'active', :t, 1) RETURNING id",
            u=user_id,
            d=NOW.date(),
            t=NOW,
        )

    def conversation(
        self,
        user_id: uuid.UUID,
        *,
        source: str = "specific",
        day_session_id: uuid.UUID | None = None,
        segment_order: int | None = None,
    ) -> uuid.UUID:
        return self.scalar(
            "INSERT INTO conversations (user_id, day_session_id, local_date, timezone, source,"
            " status, started_at, segment_order, sync_rev)"
            " VALUES (:u, :ds, :d, 'Asia/Kolkata', :src, 'active', :t, :so, 1) RETURNING id",
            u=user_id,
            ds=day_session_id,
            d=NOW.date(),
            src=source,
            t=NOW,
            so=segment_order,
        )

    def message(
        self,
        user_id: uuid.UUID,
        conversation_id: uuid.UUID,
        *,
        stream_id: uuid.UUID | None = None,
        event_key: str = "final-1",
        original_text: str = "hello",
        timestamp_source: str = "server_received",
    ) -> uuid.UUID:
        return self.scalar(
            "INSERT INTO transcript_messages (user_id, conversation_id, source_stream_id,"
            " source_event_key, original_text, search_text, search_norm_version,"
            " timestamp_source, started_at, sync_rev)"
            " VALUES (:u, :c, :s, :k, :o, :o, 1, :ts, :t, 1) RETURNING id",
            u=user_id,
            c=conversation_id,
            s=stream_id or uuid.uuid4(),
            k=event_key,
            o=original_text,
            ts=timestamp_source,
            t=NOW,
        )

    def checkpoint(
        self,
        user_id: uuid.UUID,
        *,
        status: str = "active",
        conversation_id: uuid.UUID | None = None,
        client_stream_id: uuid.UUID | None = None,
    ) -> uuid.UUID:
        stream_id = client_stream_id or uuid.uuid4()
        self.execute(
            "INSERT INTO stream_checkpoints (user_id, conversation_id, client_stream_id, status)"
            " VALUES (:u, :c, :s, :st)",
            u=user_id,
            c=conversation_id,
            s=stream_id,
            st=status,
        )
        return stream_id


def quoted(schema: str) -> str:
    # Schema names are generated by the fixture from a UUID (hex only), never from input.
    return '"' + schema + '"'
